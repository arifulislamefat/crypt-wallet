//! BIP-39 mnemonic generation, import, and seed derivation.
//!
//! Security-critical module. Two rules govern everything here:
//! 1. Entropy for a *new* mnemonic must come from the OS CSPRNG, full stop.
//! 2. Once a mnemonic or seed exists in memory, it must be wrapped in a type
//!    that (a) zeroizes on drop and (b) cannot be accidentally printed,
//!    logged, or serialized by a caller who isn't specifically trying to.

use bip39::{Language, Mnemonic};
use rand_core::OsRng;
use zeroize::ZeroizeOnDrop;

/// Supported mnemonic lengths for *generation*. BIP-39 itself also allows
/// 15/18/21 words; those are still accepted on *import* (see
/// [`SecretMnemonic::import`]) for compatibility with phrases generated by
/// other wallets, but Crypt Wallet only ever generates 12 or 24, per the
/// product decision in the architecture spec (§D.1: default new wallets to
/// 24 words, offer 12 for users who explicitly choose it).
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum WordCount {
    /// 128 bits of entropy.
    Twelve = 12,
    /// 256 bits of entropy.
    TwentyFour = 24,
}

/// Errors from mnemonic generation or import.
///
/// Deliberately opaque: no variant carries the invalid phrase or any part of
/// it, so printing this error can never leak partial secret data — including
/// via a crash reporter that captures `Display`/`Debug` output of a returned
/// `Err`, which is a real leak path if you're not careful about it.
#[derive(Debug, thiserror::Error, PartialEq, Eq)]
pub enum MnemonicError {
    /// The OS RNG or the underlying BIP-39 generator failed.
    #[error("failed to generate mnemonic from secure randomness")]
    GenerationFailed,
    /// Import failed: wrong word count, a word not in the wordlist, or a
    /// checksum mismatch. Intentionally not distinguished further in the
    /// public error — telling an attacker *which* of these three failed is
    /// a very small oracle, but an unnecessary one, and the UI-level message
    /// to the user should be the same either way ("check your recovery
    /// phrase and try again").
    #[error("invalid mnemonic: wrong word count, unknown word, or bad checksum")]
    InvalidMnemonic,
}

/// A BIP-39 mnemonic held in memory, zeroized on drop, never `Debug`-printed
/// in full, never `Serialize`.
#[derive(ZeroizeOnDrop)]
pub struct SecretMnemonic {
    inner: Mnemonic,
}

impl std::fmt::Debug for SecretMnemonic {
    fn fmt(&self, f: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {
        // Deliberately does not call self.inner's Display/Debug. This is the
        // single line standing between "developer runs dbg!(mnemonic) while
        // debugging and it ends up in a shared log" and "it doesn't."
        f.write_str("SecretMnemonic(<redacted>)")
    }
}

impl SecretMnemonic {
    /// Generate a brand-new mnemonic from the OS CSPRNG.
    ///
    /// Security decision: this function constructs `OsRng` internally rather
    /// than accepting a caller-supplied `impl RngCore`. That's a narrower,
    /// less "flexible" API on purpose — it makes it structurally impossible
    /// for a future caller (including a well-intentioned test helper) to
    /// wire in a non-cryptographic RNG for "convenience" and have that
    /// silently ship to production. If you need deterministic mnemonics for
    /// a test, use `from_entropy_for_testing` below, which is explicit about
    /// what it is and is not exported outside `#[cfg(test)]`.
    pub fn generate(word_count: WordCount) -> Result<Self, MnemonicError> {
        let mut rng = OsRng;
        let inner = Mnemonic::generate_in_with(&mut rng, Language::English, word_count as usize)
            .map_err(|_| MnemonicError::GenerationFailed)?;
        Ok(Self { inner })
    }

    /// Import and validate an existing mnemonic phrase.
    ///
    /// The BIP-39 checksum is verified as part of parsing — an invalid
    /// checksum is rejected here, not silently accepted. Words are matched
    /// against the official English BIP-39 wordlist; other BIP-39 languages
    /// are not enabled in this build (see Cargo.toml features) and are a
    /// deliberate scope decision to flag with you, not an oversight — added
    /// language support should come with its own review, since it changes
    /// the checksum/normalization code paths exercised.
    pub fn import(phrase: &str) -> Result<Self, MnemonicError> {
        let inner = Mnemonic::parse_normalized(phrase).map_err(|_| MnemonicError::InvalidMnemonic)?;
        Ok(Self { inner })
    }

    /// Derive the 64-byte BIP-39 seed.
    ///
    /// `passphrase` is the optional BIP-39 "25th word" / extension
    /// passphrase — pass `""` if the user hasn't set one. Note this is a
    /// *different* secret from the app unlock passcode used for at-rest
    /// encryption (§D.3 of the architecture spec) — conflating the two would
    /// mean changing your app passcode silently changes which addresses your
    /// seed derives, which is a serious, easy-to-make design mistake in
    /// wallets. Keep them structurally separate in the calling code.
    pub fn to_seed(&self, passphrase: &str) -> Seed {
        Seed(self.inner.to_seed_normalized(passphrase))
    }

    /// Number of words in this mnemonic (12, 15, 18, 21, or 24).
    pub fn word_count(&self) -> usize {
        self.inner.word_count()
    }

    /// Render the phrase as a `String`, for one-time display on a
    /// screenshot-blocked, re-authenticated backup/reveal screen only.
    ///
    /// Callers MUST NOT log this value, pass it to any analytics/crash
    /// framework, write it to disk unencrypted, or hold it longer than the
    /// screen needs it. This function returning a `String` rather than
    /// something zeroizing is a conscious trade-off for Phase 1 simplicity —
    /// **flagging this as a follow-up hardening item**: the UI layer should
    /// wrap the returned `String` in its own zeroize-on-drop holder
    /// immediately, since a bare `String` here will leave a copy in the
    /// allocator until overwritten, and `String` does not zeroize itself.
    pub fn reveal(&self) -> String {
        self.inner.to_string()
    }

    /// Construct a mnemonic from explicit entropy, for use in tests only —
    /// e.g. reproducing the official BIP-39 test vectors, where the entropy
    /// is fixed by the spec rather than randomly generated.
    ///
    /// Not exported outside the crate's test target: there is no path from
    /// production code to a non-random mnemonic.
    #[cfg(test)]
    pub(crate) fn from_entropy_for_testing(entropy: &[u8]) -> Result<Self, MnemonicError> {
        let inner = Mnemonic::from_entropy(entropy).map_err(|_| MnemonicError::GenerationFailed)?;
        Ok(Self { inner })
    }

    /// Expose the phrase for equality checks in tests only.
    #[cfg(test)]
    pub(crate) fn phrase_for_testing(&self) -> String {
        self.inner.to_string()
    }
}

/// A 64-byte BIP-39 seed, zeroized on drop, never `Debug`-printed in full.
#[derive(ZeroizeOnDrop)]
pub struct Seed(pub(crate) [u8; 64]);

impl std::fmt::Debug for Seed {
    fn fmt(&self, f: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {
        f.write_str("Seed(<redacted>)")
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    /// Official BIP-39 test vector (24-word, all-zero entropy), as published
    /// in https://github.com/trezor/python-mnemonic/blob/master/vectors.json
    /// — the canonical reference vector set every BIP-39 implementation is
    /// checked against.
    ///
    /// This exact seed value was independently re-derived during the
    /// writing of this module using Python's stdlib
    /// `hashlib.pbkdf2_hmac('sha512', mnemonic, b"mnemonic"+passphrase, 2048)`
    /// (the PBKDF2 construction BIP-39 §"From mnemonic to seed" specifies),
    /// confirming the vector below byte-for-byte before it was hard-coded
    /// here — not copied from a single unverified source.
    #[test]
    fn official_bip39_test_vector_all_zero_entropy() {
        let entropy = [0u8; 32]; // 256 bits of zero entropy -> 24-word mnemonic
        let mnemonic = SecretMnemonic::from_entropy_for_testing(&entropy)
            .expect("fixed test entropy must be valid");

        assert_eq!(mnemonic.word_count(), 24);
        assert_eq!(
            mnemonic.phrase_for_testing(),
            "abandon abandon abandon abandon abandon abandon abandon abandon abandon abandon \
             abandon abandon abandon abandon abandon abandon abandon abandon abandon abandon \
             abandon abandon abandon art"
        );

        let seed = mnemonic.to_seed("TREZOR");
        let expected_seed_hex =
            "bda85446c68413707090a52022edd26a1c9462295029f2e60cd7c4f2bbd3097170af7a4d73245c\
             afa9c3cca8d561a7c3de6f5d4a10be8ed2a5e608d68f92fcc8";
        assert_eq!(hex::encode(seed.0), expected_seed_hex);
    }

    #[test]
    fn generate_produces_requested_word_count() {
        let m12 = SecretMnemonic::generate(WordCount::Twelve).expect("generation should succeed");
        assert_eq!(m12.word_count(), 12);

        let m24 = SecretMnemonic::generate(WordCount::TwentyFour).expect("generation should succeed");
        assert_eq!(m24.word_count(), 24);
    }

    #[test]
    fn two_generated_mnemonics_are_never_equal() {
        // Not a formal randomness test (that belongs in a statistical test
        // suite against the RNG itself, not here) — this is a cheap sanity
        // check that generation isn't accidentally deterministic (e.g. a
        // hard-coded seed left in from testing, or an RNG that wasn't wired
        // up correctly).
        let a = SecretMnemonic::generate(WordCount::TwentyFour).expect("generation should succeed");
        let b = SecretMnemonic::generate(WordCount::TwentyFour).expect("generation should succeed");
        assert_ne!(a.phrase_for_testing(), b.phrase_for_testing());
    }

    #[test]
    fn import_round_trip_preserves_phrase() {
        let original = SecretMnemonic::generate(WordCount::Twelve).expect("generation should succeed");
        let phrase = original.phrase_for_testing();

        let imported = SecretMnemonic::import(&phrase).expect("re-importing our own phrase must succeed");
        assert_eq!(imported.phrase_for_testing(), phrase);
    }

    #[test]
    fn import_rejects_bad_checksum() {
        // Same 24 words as the official test vector, but with the final
        // checksum word swapped for another valid wordlist word — this
        // must be rejected, not silently "corrected" or accepted.
        let tampered = "abandon abandon abandon abandon abandon abandon abandon abandon abandon \
                         abandon abandon abandon abandon abandon abandon abandon abandon abandon \
                         abandon abandon abandon abandon abandon zoo";
        let result = SecretMnemonic::import(tampered);
        assert_eq!(result.err(), Some(MnemonicError::InvalidMnemonic));
    }

    #[test]
    fn import_rejects_wrong_word_count() {
        let too_short = "abandon abandon abandon";
        let result = SecretMnemonic::import(too_short);
        assert_eq!(result.err(), Some(MnemonicError::InvalidMnemonic));
    }

    #[test]
    fn import_rejects_unknown_word() {
        let with_garbage = "abandon abandon abandon abandon abandon abandon abandon abandon \
                             abandon abandon abandon notarealbip39word";
        let result = SecretMnemonic::import(with_garbage);
        assert_eq!(result.err(), Some(MnemonicError::InvalidMnemonic));
    }

    #[test]
    fn same_mnemonic_and_passphrase_always_yields_same_seed() {
        let entropy = [0x7fu8; 16]; // arbitrary fixed entropy, 128 bits -> 12 words
        let m1 = SecretMnemonic::from_entropy_for_testing(&entropy).expect("valid entropy");
        let m2 = SecretMnemonic::from_entropy_for_testing(&entropy).expect("valid entropy");

        assert_eq!(m1.to_seed("").0, m2.to_seed("").0);
    }

    #[test]
    fn different_passphrase_yields_different_seed() {
        // This is the property that makes the BIP-39 passphrase meaningful
        // as a second factor ("25th word") — if this ever fails, the
        // passphrase feature is silently doing nothing.
        let entropy = [0x7fu8; 16];
        let m = SecretMnemonic::from_entropy_for_testing(&entropy).expect("valid entropy");
        assert_ne!(m.to_seed("").0, m.to_seed("some-passphrase").0);
    }

    #[test]
    fn debug_output_never_contains_the_phrase() {
        let m = SecretMnemonic::generate(WordCount::Twelve).expect("generation should succeed");
        let phrase = m.phrase_for_testing();
        let debug_output = format!("{m:?}");

        assert_eq!(debug_output, "SecretMnemonic(<redacted>)");
        // Belt-and-braces: also confirm none of the individual words leaked.
        for word in phrase.split_whitespace() {
            assert!(!debug_output.contains(word));
        }
    }
}
